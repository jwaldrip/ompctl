/**
 * Prove the container host backend, end to end, against a real container.
 *
 * The unit tests for `ContainerBackend` mock the runtime, so they can only show
 * that the right argv was assembled. This drives the whole path: a daemon on
 * its own port and home, `POST /v1/agents` with a `kind: "container"` spec, an
 * `omp acp` inside the container, a real model turn answered through the
 * daemon's own model broker, the approval gate answered over the client
 * websocket, and the grant refused once the agent is gone.
 *
 * What it no longer does, which is the point of this version.
 *
 * Until this rewrite the script copied the operator's `~/.omp/agent/agent.db`
 * into the mounted workspace so the guest could reach a model. The snapshot was
 * pruned to one provider and seven private tables were emptied, and none of
 * that made it safe: what crossed was still a real Anthropic OAuth credential,
 * sitting on a filesystem the guest could read, in a container that keeps full
 * unrestricted internet egress. Narrowing a reusable credential is not
 * confining it. Anything reusable that reaches a guest is off this machine the
 * moment the image is hostile, and the sandbox offers nothing to fall back on.
 * The docs now say ompd never hands a container a provider credential, and a
 * check script that did would be the repo violating its own claim.
 *
 * So the guest gets what a provisioned agent gets: a scoped bearer for exactly
 * one model on exactly one endpoint, the daemon's broker, which forwards to
 * `omp auth-gateway` on the host's loopback and resolves the operator's
 * credential there. The bearer is random, pinned to this container's network,
 * capped, and revoked on teardown. It is worth nothing anywhere else and
 * nothing at all afterwards, and the phases below assert both rather than
 * assuming them: the credential-shape scan is proved against a planted decoy
 * first, and the revocation probe refuses to read an unreachable broker as a
 * pass.
 *
 * The gate is the other part worth the trouble. `spawnLocalHost` writes the
 * overlay described in `docs/acp-approval-gate.md` to a path on the daemon's
 * machine, which does not exist inside the container; `gate-wrapper.ts` places
 * it in a directory the container has mounted read-only at `/run/ompd-gate`
 * and byte-verifies it on the daemon's own side, so the far side only ever
 * reads. Nothing about that had ever been watched against a real container.
 * An approval frame arriving at ompd at all is what proves the ACP permission
 * hook ran, since nothing else emits one; the failure text says which of the
 * two gates refused; and the overlay being unwritable from inside is what
 * stops the container serving itself a permissive one instead.
 *
 * One property was lost with the credential copy and is worth naming rather
 * than quietly dropping: the old snapshot carried the operator's `config.yml`
 * verbatim, `tools.approvalMode: yolo` and all, so a container that still asked
 * for approval proved the daemon's overlay outranked the guest's own config.
 * The guest's `config.yml` is now generated by the daemon and carries model
 * roles only, so that precedence is no longer exercised here. It belongs in a
 * unit test over the overlay, not in a script that has to be handed a
 * credential to express it.
 *
 * Everything it creates is removed, including on the failure path: the
 * container, the workspace, the daemon home, and the image unless
 * `--keep-image` is given.
 *
 * Usage:
 *   bun run scripts/check-container-host.ts [--keep-image] [--image <tag>]
 */

